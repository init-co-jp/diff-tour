// Package i18n holds the UI messages for each language. Tour content is shown in the language of the tour data as is.
package i18n

import (
	"fmt"
	"os"
	"strings"
)

type Lang string

const (
	EN Lang = "en"
	JA Lang = "ja"
	ZH Lang = "zh" // Simplified Chinese
	// ZHHant is Traditional Chinese, worded for readers in Taiwan (Hong Kong and Macau get it too).
	ZHHant Lang = "zh-Hant"
	ES     Lang = "es"
	RU     Lang = "ru"
)

// Langs lists the supported languages. It is also the order of the choices.
var Langs = []Lang{EN, JA, ZH, ZHHant, ES, RU}

func (l Lang) Name() string {
	switch l {
	case JA:
		return "日本語"
	case ZH:
		return "简体中文"
	case ZHHant:
		return "繁體中文"
	case ES:
		return "Español"
	case RU:
		return "Русский"
	default:
		return "English"
	}
}

func Parse(s string) (Lang, bool) {
	if l, ok := chinese(s); ok {
		return l, true
	}
	for _, l := range Langs {
		if strings.EqualFold(s, string(l)) {
			return l, true
		}
	}
	return EN, false
}

var current = EN

func Set(l Lang) { current = l }

func Current() Lang { return current }

// Detect picks a language from the terminal's locale settings (LC_ALL -> LC_MESSAGES -> LANG).
// If the language isn't supported, it uses English. It also returns which variable it read from.
func Detect() (Lang, string) {
	for _, key := range []string{"LC_ALL", "LC_MESSAGES", "LANG"} {
		v := os.Getenv(key)
		if v == "" || v == "C" || v == "POSIX" {
			continue
		}
		locale := strings.SplitN(strings.SplitN(v, ".", 2)[0], "@", 2)[0]
		if l, ok := chinese(locale); ok {
			return l, key + "=" + v
		}
		code := strings.ToLower(strings.SplitN(locale, "_", 2)[0])
		l, ok := Parse(code)
		if !ok {
			l = EN
		}
		return l, key + "=" + v
	}
	return EN, ""
}

// chinese reads a Chinese language tag or locale such as zh, zh-CN, zh_TW or zh-Hant-HK. Traditional script
// (Hant) and the regions that write it (Taiwan, Hong Kong, Macau) get ZHHant, and the rest ZH.
func chinese(s string) (Lang, bool) {
	parts := strings.FieldsFunc(strings.ToLower(s), func(r rune) bool { return r == '-' || r == '_' })
	if len(parts) == 0 || parts[0] != "zh" {
		return "", false
	}
	for _, p := range parts[1:] {
		switch p {
		case "hans":
			return ZH, true
		case "hant", "tw", "hk", "mo":
			return ZHHant, true
		}
	}
	return ZH, true
}

// T returns the message for the current language, falling back to English if that language lacks it.
func T(key string, args ...any) string {
	m, ok := messages[current][key]
	if !ok {
		m, ok = messages[EN][key]
	}
	if !ok {
		return key
	}
	if len(args) > 0 {
		return fmt.Sprintf(m, args...)
	}
	return m
}

